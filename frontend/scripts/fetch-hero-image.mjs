import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

// Wikimedia asks for a descriptive User-Agent. Put the team's real contact email here.
const UA = 'GREMS-college-project/1.0 (educational DBMS mini project; contact: your-email@example.com)';
const API = 'https://commons.wikimedia.org/w/api.php';

// Preferred file first, then fall back to Commons search results.
const CANDIDATES = ['File:Rashtrapati Bhavan Wide New Delhi India.jpg'];
const SEARCH_TERMS = [
  'Rashtrapati Bhavan New Delhi',
  'Rashtrapati Bhavan Raisina Hill',
  'Parliament House Sansad Bhavan New Delhi',
];

const MIN_WIDTH = 2400;                                  // "high resolution"
const LICENSE_OK = /^(CC BY(-SA)? \d\.\d|CC0|Public domain|PD)/i; // rejects NC / ND automatically
const SIZES = [768, 1280, 1920];

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '..');
const outDir = path.join(root, 'public', 'images', 'hero');

async function api(params) {
  const url = `${API}?${new URLSearchParams({ format: 'json', origin: '*', ...params })}`;
  const res = await fetch(url, { headers: { 'User-Agent': UA } });
  if (!res.ok) throw new Error(`Commons API ${res.status} ${res.statusText}`);
  return res.json();
}

async function inspect(title) {
  const json = await api({ action: 'query', titles: title, prop: 'imageinfo', iiprop: 'url|size|mime|extmetadata' });
  const page = Object.values(json.query.pages)[0];
  const ii = page?.imageinfo?.[0];
  if (!ii) return null;
  const m = ii.extmetadata ?? {};
  return {
    title: page.title,
    width: ii.width,
    height: ii.height,
    mime: ii.mime,
    license: m.LicenseShortName?.value ?? '',
    licenseUrl: m.LicenseUrl?.value ?? '',
    author: (m.Artist?.value ?? '').replace(/<[^>]+>/g, '').replace(/\s+/g, ' ').trim(),
    sourceUrl: ii.descriptionurl,
  };
}

function acceptable(i) {
  if (!i) return 'no image info';
  if (i.mime !== 'image/jpeg') return `mime ${i.mime}`;
  if (i.width < MIN_WIDTH) return `too small (${i.width}px)`;
  const ratio = i.width / i.height;
  if (ratio < 1.3 || ratio > 2.2) return `bad aspect ratio ${ratio.toFixed(2)}`;
  if (!LICENSE_OK.test(i.license)) return `license not allowed (${i.license || 'unknown'})`;
  if (!i.author) return 'author missing';
  return null; // OK
}

async function pickImage() {
  const titles = [...CANDIDATES];
  for (const term of SEARCH_TERMS) {
    const json = await api({ action: 'query', list: 'search', srsearch: term, srnamespace: '6', srlimit: '15' });
    titles.push(...json.query.search.map((s) => s.title));
  }
  for (const title of [...new Set(titles)]) {
    const info = await inspect(title);
    const problem = acceptable(info);
    if (!problem) return info;
    console.log(`skip  ${title}: ${problem}`);
  }
  throw new Error('No acceptable image found on Commons.');
}

async function download(title, width, dest) {
  const name = title.replace(/^File:/, '').replace(/ /g, '_');
  const url = `https://commons.wikimedia.org/wiki/Special:FilePath/${encodeURIComponent(name)}?width=${width}`;
  const res = await fetch(url, { headers: { 'User-Agent': UA }, redirect: 'follow' });
  if (!res.ok) throw new Error(`Download ${width}px failed: ${res.status}`);
  const buf = Buffer.from(await res.arrayBuffer());
  await writeFile(dest, buf);
  return buf.length;
}

const chosen = await pickImage();
console.log(`use   ${chosen.title} (${chosen.width}x${chosen.height}, ${chosen.license}, by ${chosen.author})`);

await mkdir(outDir, { recursive: true });
for (const w of SIZES) {
  const bytes = await download(chosen.title, w, path.join(outDir, `hero-${w}.jpg`));
  console.log(`saved hero-${w}.jpg  ${(bytes / 1024).toFixed(0)} KB`);
}

const credit = {
  title: chosen.title.replace(/^File:/, ''),
  author: chosen.author,
  license: chosen.license,
  licenseUrl: chosen.licenseUrl,
  sourceUrl: chosen.sourceUrl,
  originalWidth: chosen.width,
  originalHeight: chosen.height,
  ratio: chosen.width / chosen.height,
  widths: SIZES,
};
await mkdir(path.join(root, 'src', 'data'), { recursive: true });
await writeFile(
  path.join(root, 'src', 'data', 'imageCredits.js'),
  `// Generated by scripts/fetch-hero-image.mjs. Do not edit by hand.\nexport const heroImage = ${JSON.stringify(credit, null, 2)};\n`,
);
console.log('wrote src/data/imageCredits.js');
